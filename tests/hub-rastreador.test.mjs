import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const raiz = new URL('../', import.meta.url).pathname, ler = (p) => readFileSync(raiz + p, 'utf8');
const g = {}; new Function('globalThis', ler('status-cartoes.js'))(g);
const S = g.StatusCartoes;
assert.equal(S.porIdade(60), 'online'); assert.equal(S.porIdade(1800), 'atrasado'); assert.equal(S.porIdade(9000), 'parado'); assert.equal(S.porIdade(null), null);
const agora = Date.parse('2026-10-22T12:00:00Z');
assert.equal(S.ultimaData({ a: '2026-10-22T11:00:00Z', b: { c: '2026-10-22T11:30:00.5Z' }, f: '2027-01-01T00:00:00Z' }, agora), Date.parse('2026-10-22T11:30:00.5Z'));
assert.equal(S.ultimaData({}, agora), null);
const st = ler('status-cartoes.js');
assert.ok(/Sem dados/.test(st) && /comTempo/.test(st), 'fallback Sem dados com tempo limite');
const hub = ler('app/index.html');
for (const h of ['../rastreador/', '../utilities/', '../consumo/', './relatorio/', '../admin/acessos/']) assert.ok(hub.includes('href="' + h), 'hub sem ' + h);
assert.ok(!hub.includes('relatorio-demo'), 'demo fora do hub');
assert.ok(!/Asset Tracker|Deutsche Telekom IoT/.test(hub), 'painel saiu do hub');
const icos = [...hub.matchAll(/#i-([a-z]+)/g)].map((m) => m[1]); assert.equal(new Set(icos).size, icos.length, 'ícones repetidos no hub');
const sel = ler('rastreador/index.html');
assert.ok(sel.includes('href="thingy91x/"') && sel.includes('href="../ntn/"') && sel.includes('data-pagina="rastreador"'));
assert.ok(existsSync(raiz + 'rastreador/thingy91x/index.html'));
const pn = ler('rastreador/thingy91x/index.html');
assert.ok(pn.includes('data-pagina="thingy91x"') && pn.includes('thingy-v2.js') && !pn.includes('id="configBtn"'));
assert.ok(ler('rastreador/thingy91x/classico.html').includes('../app.js'));
assert.ok(/ntn-v59/.test(ler('service-worker.js')));
assert.ok(/\/thingy91x \/rastreador\/thingy91x\/ 301/.test(ler('_redirects')));
console.log('ok  - hub, seleção de rastreador, status com fallback e redirecionamentos');
